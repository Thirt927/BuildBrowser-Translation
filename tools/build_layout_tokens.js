// Generate the class -> #token table of the layouts we ship.
//
// Why this exists: a Label declared as text="#Token" whose localized value is a
// {s:var} template is driven by SetDialogVariable, not by .text. When the
// translator assigns .text it destroys the template, and every later engine
// update is silently dropped -- the label then shows the first translation
// forever. The scanner needs to know each label's #token so it can hand the
// label back to the engine (restore the token) when a new build/item appears.
//
// Usage:
//   node tools/build_layout_tokens.js            # (re)generate
//   node tools/build_layout_tokens.js --check    # verify the shipped file is in sync
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const LAYOUT_DIR = path.join(ROOT, "mod", "panorama", "layout");
const OUT_JS = path.join(ROOT, "mod", "panorama", "scripts", "bba_layout_tokens.js");

function listLayouts(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...listLayouts(p));
    else if (e.name.endsWith(".xml")) out.push(p);
  }
  return out;
}

// A class is only usable as a key when it is a single token and not one of the
// generic style classes ("Medium Fill" etc.).
function usableClass(cls) {
  if (!cls) return null;
  const parts = cls.split(/\s+/).filter(Boolean);
  if (parts.length !== 1) return null;
  if (parts[0].length < 3) return null;
  if (/^(Fill|Small|Large|Medium|NoHover|Hide|Show)/.test(parts[0])) return null;
  return parts[0];
}

function collect() {
  const table = {}; // class -> token
  const byId = {}; // id -> token
  const conflicts = [];
  for (const file of listLayouts(LAYOUT_DIR)) {
    const xml = fs.readFileSync(file, "utf8");
    const re = /<(Label|TextButton|Button|Panel)([^>]*?)\/?>/g;
    let m;
    while ((m = re.exec(xml))) {
      const attrs = m[2];
      const tk = /text="([^"]*)"/.exec(attrs);
      if (!tk) continue;
      const text = tk[1];
      // Only tokens (the game fills them) and {s:var} templates matter.
      if (!(text.startsWith("#") || /\{[sgd]:/.test(text))) continue;
      const cls = usableClass((/class="([^"]*)"/.exec(attrs) || [])[1]);
      const id = (/id="([^"]*)"/.exec(attrs) || [])[1];
      if (cls) {
        if (table[cls] && table[cls] !== text) conflicts.push(cls + ": " + table[cls] + " vs " + text);
        else table[cls] = text;
      }
      if (id) {
        if (byId[id] && byId[id] !== text) conflicts.push("#" + id + ": " + byId[id] + " vs " + text);
        else byId[id] = text;
      }
    }
  }
  return { table, byId, conflicts };
}

function render(table, byId) {
  const sort = (o) => {
    const out = {};
    for (const k of Object.keys(o).sort()) out[k] = o[k];
    return out;
  };
  return (
    "// Generated by tools/build_layout_tokens.js - do not edit by hand.\n" +
    "// class/id -> the text=\"...\" the shipped layout declares for that label.\n" +
    "// Used by bba_translate.js to restore a token-bound label to the engine when\n" +
    "// a new build/item is shown (see the rebind logic there).\n" +
    "(function () {\n" +
    "  var g = globalThis || this || {};\n" +
    "  g.BBA_LAYOUT_TOKENS = {\n" +
    "    byClass: " + JSON.stringify(sort(table)) + ",\n" +
    "    byId: " + JSON.stringify(sort(byId)) + ",\n" +
    "  };\n" +
    "})();\n"
  );
}

const { table, byId, conflicts } = collect();
const body = render(table, byId);

if (process.argv.indexOf("--check") >= 0) {
  const cur = fs.existsSync(OUT_JS) ? fs.readFileSync(OUT_JS, "utf8") : "";
  if (cur !== body) {
    console.error("bba_layout_tokens.js is out of date; run: node tools/build_layout_tokens.js");
    process.exit(1);
  }
  console.log("layout token table in sync (" + Object.keys(table).length + " classes, " + Object.keys(byId).length + " ids)");
  process.exit(0);
}

fs.writeFileSync(OUT_JS, body);
console.log(
  "wrote " + path.relative(ROOT, OUT_JS) + ": " + Object.keys(table).length + " classes, " +
    Object.keys(byId).length + " ids",
);
if (conflicts.length) {
  console.warn("conflicting declarations (first wins):");
  for (const c of conflicts) console.warn("  " + c);
}
