// BuildBrowser Translation - compact translation-memory encoder/decoder.
//
// Why: the original bba_tm.js was one huge object literal (58k keys), which
// costs ~13 MiB of heap and ~75 ms of parse time *per layout context*. Panorama
// gives every layout its own JS context, and five layouts ship the TM, so the
// old format cost ~67 MiB and five parse hitches. The compact format keeps the
// same key -> value lookups in a single flat string plus an offset table:
// roughly 2.5 MiB of heap and a few ms of boot work per context.
//
// Wire format (one JS string `D`, records sorted by key):
//   key \t escapedValue \n
// Escapes inside escapedValue:  \\  ->  \   \n -> newline   \t -> tab
// Keys are the 32-bit hash pair produced by textKey(), so they never contain
// a tab, a newline or a backslash.
"use strict";

const TAB = "\t";
const NL = "\n";

function escapeValue(v) {
  return String(v == null ? "" : v)
    .replace(/\\/g, "\\\\")
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t");
}

function unescapeValue(v) {
  let out = "";
  for (let i = 0; i < v.length; i += 1) {
    const c = v[i];
    if (c !== "\\" || i + 1 >= v.length) {
      out += c;
      continue;
    }
    const n = v[i + 1];
    i += 1;
    if (n === "n") out += "\n";
    else if (n === "t") out += "\t";
    else out += n;
  }
  return out;
}

/** Serialize a { key: value } map into the flat record string (sorted by key). */
function encode(map) {
  const keys = Object.keys(map).sort();
  const parts = new Array(keys.length);
  for (let i = 0; i < keys.length; i += 1) {
    parts[i] = keys[i] + TAB + escapeValue(map[keys[i]]) + NL;
  }
  return parts.join("");
}

/** Minimal JS source for the in-game side: publishes BBA_TM_GET / BBA_TM_COUNT. */
function emitScript(map, meta) {
  const data = encode(map);
  const count = Object.keys(map).length;
  const gen = (meta && meta.generated_at) || "";
  return (
    "// BuildBrowser Translation - translation memory (compact format).\n" +
    "// Generated by tools/build_tm.js / tools/tm_compact.js - do not edit by hand.\n" +
    "// " + count + " entries" + (gen ? ", generated " + gen : "") + ".\n" +
    "// Records are sorted by key: binary search over an offset table instead of a\n" +
    "// 58k-key object literal (13 MiB -> ~4 MiB per layout context).\n" +
    "(function () {\n" +
    "  var COUNT = " + count + ";\n" +
    "  var D = " + JSON.stringify(data) + ";\n" +
    "  var L = D.length;\n" +
    "  // Int32 offset table (~233 KiB) instead of a 58k-element object/array.\n" +
    "  var off = typeof Int32Array === \"function\" ? new Int32Array(COUNT + 1) : [];\n" +
    "  var n = 0;\n" +
    "  var p = 0;\n" +
    "  while (p <= L && n <= COUNT) {\n" +
    "    off[n] = p;\n" +
    "    n += 1;\n" +
    "    var q = D.indexOf(\"\\n\", p);\n" +
    "    if (q < 0) break;\n" +
    "    p = q + 1;\n" +
    "  }\n" +
    "  n -= 1;\n" +
    "  if (n < 0) n = 0;\n" +
    "  function unesc(v) {\n" +
    "    if (v.indexOf(\"\\\\\") < 0) return v;\n" +
    "    var out = \"\", i = 0;\n" +
    "    while (i < v.length) {\n" +
    "      var c = v.charAt(i);\n" +
    "      if (c !== \"\\\\\" || i + 1 >= v.length) { out += c; i += 1; continue; }\n" +
    "      var x = v.charAt(i + 1);\n" +
    "      out += x === \"n\" ? \"\\n\" : x === \"t\" ? \"\\t\" : x;\n" +
    "      i += 2;\n" +
    "    }\n" +
    "    return out;\n" +
    "  }\n" +
    "  function get(k) {\n" +
    "    var lo = 0, hi = n - 1;\n" +
    "    while (lo <= hi) {\n" +
    "      var mid = (lo + hi) >> 1;\n" +
    "      var s = off[mid];\n" +
    "      var t = D.indexOf(\"\\t\", s);\n" +
    "      if (t < 0) return null;\n" +
    "      var rk = D.slice(s, t);\n" +
    "      if (rk === k) return unesc(D.slice(t + 1, mid + 1 <= n ? off[mid + 1] - 1 : L));\n" +
    "      if (rk < k) lo = mid + 1; else hi = mid - 1;\n" +
    "    }\n" +
    "    return null;\n" +
    "  }\n" +
    "  var g = globalThis || this || {};\n" +
    "  g.BBA_TM_GET = get;\n" +
    "  g.BBA_TM_COUNT = " + count + ";\n" +
    "})();\n"
  );
}

/** Decode a compact record string back into a { key: value } map (for tests/tools). */
function decode(data) {
  const map = Object.create(null);
  let s = 0;
  while (s < data.length) {
    const nl = data.indexOf(NL, s);
    const end = nl < 0 ? data.length : nl;
    const tab = data.indexOf(TAB, s);
    if (tab >= 0 && tab < end) map[data.slice(s, tab)] = unescapeValue(data.slice(tab + 1, end));
    if (nl < 0) break;
    s = nl + 1;
  }
  return map;
}

/** Read the { key: value } map out of an existing bba_tm.js (any format). */
function readFromScript(source) {
  // Compact format: grab the string literal assigned to D.
  const mData = source.match(/\bvar D = ("(?:[^"\\]|\\.)*")/);
  if (mData) {
    try {
      return decode(JSON.parse(mData[1]));
    } catch (e) {
      /* fall through to the object-literal format */
    }
  }
  // Legacy object literal: var T = { ... };
  const mObj = source.match(/var T = (\{[\s\S]*?\});\s*(?:\n|$)/);
  if (mObj) return JSON.parse(mObj[1]);
  throw new Error("no translation memory found in this file");
}

module.exports = { encode, decode, emitScript, readFromScript, escapeValue, unescapeValue };

if (require.main === module) {
  const fs = require("fs");
  const path = require("path");
  const target = process.argv[2] || path.join(__dirname, "..", "mod", "panorama", "scripts", "bba_tm.js");
  const src = fs.readFileSync(target, "utf8");
  const before = src.length;
  const map = readFromScript(src);
  const out = emitScript(map, { generated_at: new Date().toISOString().slice(0, 10) });
  fs.writeFileSync(target, out);
  console.log(
    "converted " + Object.keys(map).length + " entries: " +
      (before / 1048576).toFixed(2) + " MiB -> " + (out.length / 1048576).toFixed(2) + " MiB  (" + target + ")",
  );
}
